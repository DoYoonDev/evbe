-- 회원
CREATE TABLE member (
    id                   VARCHAR2(50 CHAR) PRIMARY KEY,
    ko_name              VARCHAR2(50 CHAR),
    en_name              VARCHAR2(50 CHAR),
    email                VARCHAR2(50 CHAR),
    phone_number         VARCHAR2(50 CHAR),
    password             VARCHAR2(255 CHAR),
    is_active            BOOLEAN,
    created_at           TIMESTAMP NOT NULL,
    updated_at           TIMESTAMP NOT NULL,
    must_change_password BOOLEAN DEFAULT FALSE NOT NULL
);

-- 초기 데이터에서 정렬 순번 1~3을 사용하므로 4부터 시작
CREATE SEQUENCE code_group_sort_order_seq
    START WITH 4
    INCREMENT BY 1;

-- 코드 그룹
CREATE TABLE code_group (
    id               VARCHAR2(50 CHAR) PRIMARY KEY,
    name             VARCHAR2(50 CHAR) NOT NULL,
    description      VARCHAR2(255 CHAR) NOT NULL,
    sort_order       NUMBER(10)
                     DEFAULT code_group_sort_order_seq.NEXTVAL
                     NOT NULL,
    is_active        BOOLEAN NOT NULL,
    create_member_id VARCHAR2(50 CHAR),
    created_at       TIMESTAMP,
    update_member_id VARCHAR2(50 CHAR),
    updated_at       TIMESTAMP
);

-- 코드
CREATE TABLE code (
    id               VARCHAR2(50 CHAR) PRIMARY KEY,
    code_group_id    VARCHAR2(50 CHAR) NOT NULL,
    message_id       VARCHAR2(50 CHAR) NOT NULL,
    name             VARCHAR2(50 CHAR) NOT NULL,
    description      VARCHAR2(255 CHAR) NOT NULL,
    sort_order       NUMBER(10) NOT NULL,
    is_active        BOOLEAN NOT NULL,
    create_member_id VARCHAR2(50 CHAR),
    created_at       TIMESTAMP,
    update_member_id VARCHAR2(50 CHAR),
    updated_at       TIMESTAMP,
    CONSTRAINT fk_code_code_group
        FOREIGN KEY (code_group_id)
        REFERENCES code_group(id)
        ON DELETE CASCADE
);

CREATE INDEX idx_code_code_group_id
    ON code(code_group_id);

-- 다국어 메시지
CREATE TABLE message (
    id               VARCHAR2(255 CHAR) PRIMARY KEY,
    ko_text          CLOB NOT NULL,
    en_text          CLOB NOT NULL,
    is_active        BOOLEAN DEFAULT TRUE NOT NULL,
    create_member_id VARCHAR2(50 CHAR),
    created_at       TIMESTAMP,
    update_member_id VARCHAR2(50 CHAR),
    updated_at       TIMESTAMP
);

-- 메뉴
CREATE TABLE menu (
    id               NUMBER(10)
                     GENERATED BY DEFAULT AS IDENTITY
                     PRIMARY KEY,
    parent_menu_id   NUMBER(10),
    message_id       VARCHAR2(255 CHAR),
    url              VARCHAR2(255 CHAR),
    name             VARCHAR2(50 CHAR),
    is_active        BOOLEAN DEFAULT TRUE,
    is_delete        BOOLEAN DEFAULT FALSE,
    sort_order       NUMBER(10),
    description      CLOB,
    "level"          NUMBER(10),
    create_member_id VARCHAR2(50 CHAR),
    created_at       TIMESTAMP,
    update_member_id VARCHAR2(50 CHAR),
    updated_at       TIMESTAMP
);

-- 권한
CREATE TABLE role (
    id               VARCHAR2(50 CHAR) PRIMARY KEY,
    name             VARCHAR2(50 CHAR),
    description      VARCHAR2(255 CHAR),
    is_active        BOOLEAN,
    "level"          NUMBER(10) DEFAULT 0 NOT NULL,
    create_member_id VARCHAR2(50 CHAR),
    created_at       TIMESTAMP,
    update_member_id VARCHAR2(50 CHAR),
    updated_at       TIMESTAMP
);

-- 권한별 메뉴
CREATE TABLE role_menu (
    id      NUMBER(19)
            GENERATED BY DEFAULT AS IDENTITY
            PRIMARY KEY,
    role_id VARCHAR2(50 CHAR),
    menu_id NUMBER(10)
);

-- 회원별 권한
CREATE TABLE role_member (
    id        NUMBER(19)
              GENERATED BY DEFAULT AS IDENTITY
              PRIMARY KEY,
    role_id   VARCHAR2(50 CHAR),
    member_id VARCHAR2(50 CHAR)
);

-- 접근 로그
CREATE TABLE log_access (
    id              NUMBER(19)
                    GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
    member_id       VARCHAR2(50 CHAR),
    request_url     CLOB,
    request_method  VARCHAR2(50 CHAR),
    request_payload CLOB,
    request_ip      VARCHAR2(50 CHAR),
    response_status NUMBER(10),
    response_body   CLOB,
    user_agent      CLOB,
    created_at      TIMESTAMP
);

-- 로그인 로그
CREATE TABLE log_login (
    id         NUMBER(19)
               GENERATED BY DEFAULT AS IDENTITY
               PRIMARY KEY,
    member_id  VARCHAR2(50 CHAR),
    access_ip  VARCHAR2(50 CHAR),
    user_agent CLOB,
    success    BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP
);

-- 게시판
CREATE TABLE board (
    id                   NUMBER(19)
                         GENERATED BY DEFAULT AS IDENTITY
                         PRIMARY KEY,
    attach_file_group_id NUMBER(19),
    content              CLOB,
    title                VARCHAR2(255 CHAR),
    code_id              VARCHAR2(50 CHAR),
    create_member_id     VARCHAR2(50 CHAR),
    created_at           TIMESTAMP,
    update_member_id     VARCHAR2(50 CHAR),
    updated_at           TIMESTAMP,
    view_count           NUMBER(10) DEFAULT 0,
    is_pin               BOOLEAN DEFAULT FALSE
);

-- 첨부 파일
CREATE TABLE attach_file (
    group_id         NUMBER(19),
    id               NUMBER(19)
                     GENERATED BY DEFAULT AS IDENTITY
                     PRIMARY KEY,
    name             VARCHAR2(255 CHAR),
    save_name        VARCHAR2(255 CHAR),
    sort_order       VARCHAR2(50 CHAR),
    "size"             VARCHAR2(50 CHAR),
    extension        VARCHAR2(50 CHAR),
    path             VARCHAR2(1000 CHAR),
    create_member_id VARCHAR2(50 CHAR),
    created_at       TIMESTAMP,
    update_member_id VARCHAR2(50 CHAR),
    updated_at       TIMESTAMP
);

-- 약관
CREATE TABLE terms (
    id         VARCHAR2(50 CHAR) PRIMARY KEY,
    type       VARCHAR2(50 CHAR) NOT NULL,
    version    VARCHAR2(20 CHAR) NOT NULL,
    content    CLOB NOT NULL,
    lang_cd    VARCHAR2(10 CHAR),
    created_at TIMESTAMP WITH TIME ZONE
               DEFAULT CURRENT_TIMESTAMP
);

-- 회원 약관 동의
CREATE TABLE member_terms_agreement (
    id        VARCHAR2(50 CHAR) PRIMARY KEY,
    member_id VARCHAR2(50 CHAR),
    terms_id  VARCHAR2(50 CHAR),
    agreed    BOOLEAN DEFAULT FALSE,
    agreed_at TIMESTAMP WITH TIME ZONE
);